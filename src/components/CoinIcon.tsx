export function CoinIcon({
  coin,
  size = 32,
  className = '',
}: {
  coin: CoinId
  size?: number
  className?: string
}) {
  const [failed, setFailed] = useState(false)
  const url = coinIconUrl(coin)
  if (!url || failed) return <GlyphIcon coin={coin} size={size} className={className} />
  return (
    <img
      src={url}
      width={size}
      height={size}
      alt={COIN_MAP[coin].symbol}
      loading="lazy"
      draggable={false}
      className={`rounded-full object-cover ${className}`}
      onError={() => setFailed(true)}
    />
  )
}

